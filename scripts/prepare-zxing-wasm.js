import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const repoRoot = process.cwd()
const zxingPackageJsonPath = path.join(repoRoot, 'node_modules', 'zxing-wasm', 'package.json')
const zxingWasmSourcePath = path.join(repoRoot, 'node_modules', 'zxing-wasm', 'dist', 'reader', 'zxing_reader.wasm')
const publicDir = path.join(repoRoot, 'public')
const generatedAssetConstPath = path.join(repoRoot, 'src', 'utils', 'zxingWasmAsset.ts')

if (!existsSync(zxingPackageJsonPath)) {
  throw new Error(`Missing zxing-wasm package metadata at ${zxingPackageJsonPath}`)
}
if (!existsSync(zxingWasmSourcePath)) {
  throw new Error(`Missing zxing wasm file at ${zxingWasmSourcePath}`)
}

const zxingPackageJson = JSON.parse(readFileSync(zxingPackageJsonPath, 'utf8'))
const rawVersion = String(zxingPackageJson.version ?? '').trim()
if (!rawVersion) {
  throw new Error('Unable to determine installed zxing-wasm version')
}

const safeVersion = rawVersion.replace(/[^0-9A-Za-z.-]/g, '-')
const versionedWasmFilename = `zxing_reader-v${safeVersion}.wasm`

mkdirSync(publicDir, { recursive: true })
for (const fileName of readdirSync(publicDir)) {
  if (/^zxing_reader(?:-v[0-9A-Za-z.-]+)?\.wasm$/.test(fileName)) {
    rmSync(path.join(publicDir, fileName))
  }
}

copyFileSync(zxingWasmSourcePath, path.join(publicDir, versionedWasmFilename))

const generatedConstSource =
  `// Auto-generated by scripts/prepare-zxing-wasm.js\n` +
  `export const ZXING_WASM_FILENAME = '${versionedWasmFilename}'\n`

mkdirSync(path.dirname(generatedAssetConstPath), { recursive: true })
writeFileSync(generatedAssetConstPath, generatedConstSource, 'utf8')

console.log(`[prepare-zxing-wasm] Prepared ${versionedWasmFilename}`)
